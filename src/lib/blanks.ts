export function blanksFor(lane: BlankLane) {
  return BLANKS.filter((blank) => blank.lane === lane);
}

export function defaultBlankId(lane: "tee" | "hoodie" | "bag" | BlankLane) {
  if (lane === "hoodie") return "hood-heavy";
  if (lane === "cap") return "cap-dad";
  return "tee-classic";
}

export function blankColors(id: string) {
  return COLORS[id] ?? [];
}

export function colorOnBlank(blankId: string, colorId: string) {
  return blankColors(blankId).find((color) => color.id === colorId);
}

export function blankSizes(id: string) {
  return sizesIn(Object.keys(VARIANTS[id] ?? {}));
}

export function blankSizesFor(id: string, colorName: string) {
  const keys = Object.keys(VARIANTS[id] ?? {}).filter((key) => key.startsWith(`${colorName}|`));
  return sizesIn(keys);
}

function sizesIn(keys: string[]) {
  const sizes = new Set<string>();
  for (const key of keys) {
    const size = key.split("|")[1];
    if (size) sizes.add(size);
  }
  const order = ["XS", "S", "M", "L", "XL", "XXL", "S/M", "L/XL", "OS"];
  return order.filter((size) => sizes.has(size));
}

export function blankVariantId(blankId: string, colorName: string, size: string) {
  return VARIANTS[blankId]?.[`${colorName}|${size}`] ?? null;
}
